#!/usr/bin/env python3
"""Print public items in the named workspace crates that no workspace target uses.

rustc never reports an unused `pub` item in a library, so each crate is scanned
in a scratch copy of the working tree: every `pub` in its sources becomes
`pub(crate)`, the workspace is checked, and each line a privacy error points at
gets its `pub` back, until the workspace compiles. Each item in a grouped
`pub use a::{X, Y}` gets its own line first, so a used X cannot keep an unused
Y public. The dead_code and
unused_imports warnings left name the items nothing outside the crate reaches.
Restoring a line can only hide dead code, never invent it. Items generated by
`macro_rules!` keep their visibility and are not scanned.

Usage: find-unused-pub.py <crate>...
Prints one "<path>\t<item>" row per unused item. Reads CARGO and
CARGO_TARGET_DIR from the environment.
"""

import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

NARROW = re.compile(r"(^|[^A-Za-z_(])pub ([a-z])")
USE_GROUP = re.compile(r"(?m)^([ \t]*)pub use ([\w:]+)::\{([^{}]*)\};")
NAME = re.compile(r"`(?:[A-Za-z0-9_]+::)*([A-Za-z_][A-Za-z0-9_]*)(?:<[^`]*)?`")
MAX_ROUNDS = 60


def working_tree(repo):
    listed = subprocess.run(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        cwd=repo, check=True, capture_output=True,
    ).stdout.decode()
    return [path for path in listed.split("\0") if path and (repo / path).is_file()]


def copy_tree(repo, files, destination):
    for path in files:
        target = destination / path
        target.parent.mkdir(parents=True, exist_ok=True)
        # Fresh mtimes: cargo keys workspace artifacts by package, not by
        # directory, so a copied mtime would reuse the previous scan's build.
        shutil.copyfile(repo / path, target)


def split_use_groups(text):
    def one_per_line(match):
        indent, path, items = match.groups()
        return "\n".join(f"{indent}pub use {path}::{item.strip()};"
                         for item in items.split(",") if item.strip())
    return USE_GROUP.sub(one_per_line, text)


def narrow(text):
    lines, depth = [], 0
    for line in text.split("\n"):
        if depth or "macro_rules!" in line:
            depth += line.count("{") - line.count("}")
            lines.append(line)
        else:
            lines.append(NARROW.sub(r"\1pub(crate) \2", line))
    return "\n".join(lines)


def check(work, cargo, target_dir):
    output = subprocess.run(
        [cargo, "check", "--workspace", "--lib", "--bins", "--keep-going",
         "--message-format=json"],
        cwd=work, env={**os.environ, "CARGO_TARGET_DIR": target_dir},
        capture_output=True, text=True,
    ).stdout
    messages = []
    for raw in output.splitlines():
        try:
            message = json.loads(raw)
        except ValueError:
            continue
        if message.get("reason") == "compiler-message":
            messages.append(message["message"])
    return messages


def spans(diagnostic):
    yield from diagnostic["spans"]
    for child in diagnostic.get("children", []):
        yield from spans(child)


class Scan:
    def __init__(self, work, crate):
        self.work = work
        self.sources = sorted((work / "crates" / crate / "src").rglob("*.rs"))
        self.prefix = ("crates", crate)
        self.original = {}
        for path in self.sources:
            text = split_use_groups(path.read_text())
            self.original[path.relative_to(work)] = text.split("\n")
            path.write_text(narrow(text))

    def restore(self, rel, numbers):
        path = self.work / rel
        lines = path.read_text().split("\n")
        original = self.original[rel]
        restored = 0
        for index in (number - 1 for number in numbers):
            if index < len(original) and lines[index] != original[index]:
                lines[index] = original[index]
                restored += 1
        path.write_text("\n".join(lines))
        return restored

    def restore_by_name(self, name):
        # A re-export error points at the `use`, not at the item.
        defining = re.compile(rf"pub\(crate\) (?:[a-z]+ )*(?:[\w:]+::)?{re.escape(name)}\b")
        restored = 0
        for path in self.sources:
            rel = path.relative_to(self.work)
            numbers = [n for n, line in enumerate(path.read_text().split("\n"), 1)
                       if defining.search(line)]
            if numbers:
                restored += self.restore(rel, numbers)
        return restored

    def resolve(self, errors):
        restored = 0
        for error in errors:
            by_file = {}
            for span in spans(error):
                rel = pathlib.Path(span["file_name"])
                if not rel.is_absolute() and rel.parts[:2] == self.prefix:
                    by_file.setdefault(rel, set()).update(
                        range(span["line_start"], span["line_end"] + 1))
            found = sum(self.restore(rel, sorted(numbers)) for rel, numbers in by_file.items())
            if not found:
                found = sum(self.restore_by_name(name) for name in NAME.findall(error["message"]))
            restored += found
        return restored


def unused_items(messages, crate):
    rows = set()
    for message in messages:
        code = (message.get("code") or {}).get("code")
        if message["level"] != "warning" or code not in ("dead_code", "unused_imports"):
            continue
        span = next(span for span in message["spans"] if span["is_primary"])
        if not span["file_name"].startswith(f"crates/{crate}/"):
            continue
        for name in NAME.findall(message["message"]):
            rows.add((span["file_name"], name))
    return rows


def scan(repo, files, crate, cargo, target_dir):
    with tempfile.TemporaryDirectory() as scratch:
        work = pathlib.Path(scratch)
        copy_tree(repo, files, work)
        state = Scan(work, crate)
        for _ in range(MAX_ROUNDS):
            messages = check(work, cargo, target_dir)
            errors = [m for m in messages if m["level"] == "error" and m["spans"]]
            if not errors:
                return unused_items(messages, crate)
            if not state.resolve(errors):
                for error in errors[:5]:
                    print(error["rendered"], file=sys.stderr)
                sys.exit(f"error: cannot restore visibility in {crate}")
        sys.exit(f"error: {crate} did not compile after {MAX_ROUNDS} rounds")


def main():
    crates = sys.argv[1:]
    if not crates:
        sys.exit("usage: find-unused-pub.py <crate>...")
    repo = pathlib.Path(subprocess.run(
        ["git", "rev-parse", "--show-toplevel"], check=True, capture_output=True, text=True,
    ).stdout.strip())
    cargo = os.environ.get("CARGO", "cargo")
    target_dir = os.environ.get("CARGO_TARGET_DIR", str(repo / "target" / "unused-pub"))
    files = working_tree(repo)
    rows = set()
    for crate in crates:
        rows |= scan(repo, files, crate, cargo, target_dir)
    for path, name in sorted(rows):
        print(f"{path}\t{name}")


if __name__ == "__main__":
    main()
